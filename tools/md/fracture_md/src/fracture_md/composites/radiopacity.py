def formula_mass_fractions(formula: dict[str, float]) -> dict[str, float]:
    m = {el: n * ATOMIC_MASS[el] for el, n in formula.items()}
    t = sum(m.values())
    return {el: v / t for el, v in m.items()}


def oxide_mix(oxides_wt: dict[str, float]) -> dict[str, float]:
    """Element mass fractions of an oxide glass given oxide wt fractions."""
    ox = {"SiO2": {"Si": 1, "O": 2}, "BaO": {"Ba": 1, "O": 1}, "B2O3": {"B": 2, "O": 3}, "Al2O3": {"Al": 2, "O": 3}, "SrO": {"Sr": 1, "O": 1},
          "ZrO2": {"Zr": 1, "O": 2}, "Y2O3": {"Y": 2, "O": 3}, "Na2O": {"Na": 2, "O": 1}, "La2O3": {"La": 2, "O": 3}, "ZnO": {"Zn": 1, "O": 1}}
    out: dict[str, float] = {}
    tot = sum(oxides_wt.values())
    for o, w in oxides_wt.items():
        for el, f in formula_mass_fractions(ox[o]).items():
            out[el] = out.get(el, 0.0) + f * w / tot
    return out


